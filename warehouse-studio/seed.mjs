function localMidnight(date) {
  const pad = (value) => String(value).padStart(2, '0');
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}T00:00`;
}

export function createInitialState() {
  const now = new Date();
  const end = new Date(now.getFullYear(), now.getMonth(), now.getDate() + 7);
  const period = { start: localMidnight(now), end: localMidnight(end) };
  const warehouse = (id, name, catalog) => ({
    id, name, description: '', period: { ...period },
    items: catalog.map((item, index) => ({ id: `${id}-${index + 1}`, ...item, stock: 0, supplyMode: 'fixed', supplyAmount: 0, supplyRateUnit: 'day' })),
  });
  return {
    version: 1,
    revision: 0,
    updatedAt: now.toISOString(),
    warehouses: [
      warehouse('basic', 'Basic Supplies', basic),
      warehouse('backpack', 'Survival Backpack', backpack),
      warehouse('cooking', 'Kitchen Pantry', cooking),
    ],
  };
}
