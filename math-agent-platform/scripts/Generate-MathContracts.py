"""Generate TypeScript and JSON contracts from the Python-owned catalogue."""
import json
import sys
from pathlib import Path
root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / 'engines/mathematics/src'))
from math_engine.protocol import CATALOGUE, REQUEST_SCHEMA, RESPONSE_SCHEMA


def ts(schema):
    if 'const' in schema: return json.dumps(schema['const'])
    if 'enum' in schema: return ' | '.join(json.dumps(x) for x in schema['enum'])
    kind = schema.get('type')
    if kind == 'object':
        props = schema.get('properties')
        if props is None: return 'Record<string, unknown>'
        required = schema.get('required', [])
        return '{ ' + '; '.join(json.dumps(k) + ('' if k in required else '?') + ': ' + ts(v) for k, v in props.items()) + ' }'
    if kind == 'array': return 'Array<' + ts(schema.get('items', {})) + '>'
    return {'string': 'string', 'integer': 'number', 'number': 'number', 'boolean': 'boolean', 'null': 'null'}.get(kind, 'unknown')


schemas = {'request': REQUEST_SCHEMA, 'response': RESPONSE_SCHEMA, 'tools': CATALOGUE}
source = '// Generated by scripts/Generate-MathContracts.py. Edit the Python package, not this file.\n'
source += 'export const mathCatalogue = ' + json.dumps(CATALOGUE, indent=2) + ' as const;\n'
source += 'export const mathWireSchemas = ' + json.dumps({'request': REQUEST_SCHEMA, 'response': RESPONSE_SCHEMA}, indent=2) + ';\n'
source += 'export type MathRequest = ' + ts(REQUEST_SCHEMA) + ';\n'
source += 'export type MathResponse = {schemaVersion:1;ok:true;value:' + ts(RESPONSE_SCHEMA['properties']['value']) + '} | {schemaVersion:1;ok:false;error:{code:string;message:string}};\n'
source += 'export interface MathArguments {\n' + '\n'.join('  '+json.dumps(d['name'])+': '+ts(d['parameters'])+';' for d in CATALOGUE) + '\n}\n'
outputs = {root/'desktop/tools/math-contracts.generated.ts': source,
           root/'schemas/mathematics.schema.json': json.dumps(schemas, indent=2)+'\n'}
for path, text in outputs.items():
    if '--check' in sys.argv:
        if not path.exists() or path.read_text(encoding='utf-8') != text: raise SystemExit('Generated contract is stale: '+str(path))
    else:
        path.parent.mkdir(parents=True, exist_ok=True); path.write_text(text, encoding='utf-8')
print('Mathematics contracts verified.' if '--check' in sys.argv else 'Mathematics contracts generated.')
