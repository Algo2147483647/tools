export const source = (key) => {
  if (specialSources[key]) return specialSources[key];
  if (key.startsWith("w:")) {
    const page = decodeURIComponent(key.slice(2));
    return [
      `Wikipedia：${page.replaceAll("_", " ")}（二手综述，附参考文献）`,
      `https://en.wikipedia.org/wiki/${encodeURIComponent(page)}`,
    ];
  }
  if (/^dhm:\d{4}$/.test(key))
    return [
      `Deutsches Historisches Museum：Chronik ${key.slice(4)}`,
      `https://www.dhm.de/lemo/jahreschronik/${key.slice(4)}`,
    ];
  throw new Error(`Unknown European history source ${key}`);
};

